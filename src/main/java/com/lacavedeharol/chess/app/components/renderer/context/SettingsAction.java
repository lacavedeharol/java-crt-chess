package com.lacavedeharol.chess.app.components.renderer.context;

/**
 * Enum representing the different actions that can be performed in the settings
 * menu.
 */
enum SettingsAction {
    /** No action. */
    NONE,
    /** Toggle menu action. */
    TOGGLE_MENU,
    /** Toggle graphics menu action. */
    TOGGLE_GRAPHICS_MENU,
    /** Toggle game menu action. */
    TOGGLE_GAME_MENU,
    /** Restart action. */
    RESTART,
    /** Exit action. */
    EXIT,
    /** Toggle view action. */
    TOGGLE_VIEW,
    /** Toggle guides action. */
    TOGGLE_GUIDES,
    /** Toggle captured action. */
    TOGGLE_CAPTURED,
    /** Toggle auto queen action. */
    TOGGLE_AUTO_QUEEN,
    /** Toggle move confirm action. */
    TOGGLE_MOVE_CONFIRM
}
