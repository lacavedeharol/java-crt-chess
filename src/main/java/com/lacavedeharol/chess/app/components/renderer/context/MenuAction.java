package com.lacavedeharol.chess.app.components.renderer.context;

/**
 * Enum representing the different actions that can be performed in the menu.
 */
public enum MenuAction {
    /** No action. */
    NONE,
    /** Title action. */
    TITLE,
    /** Play game action. */
    PLAY_GAME,
    /** Configure game action. */
    CONFIGURE_GAME,
    /** Toggle side action. */
    TOGGLE_SIDE,
    /** AI difficulty action. */
    AI_DIFFICULTY,
    /** Toggle timer action. */
    TOGGLE_TIMER,
    /** Settings action. */
    SETTINGS,
    /** Exit action. */
    EXIT
}
