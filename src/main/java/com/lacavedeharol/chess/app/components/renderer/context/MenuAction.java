package com.lacavedeharol.chess.app.components.renderer.context;

/**
 * Enum representing the different actions that can be performed in the menu.
 */
enum MenuAction {
    /** No action. */
    NONE,
    /** Title action. */
    TITLE,
    /** Play game action. */
    PLAY_GAME,
    /** Configure game action. */
    CONFIGURE_GAME,
    /** Toggle side action. */
    TOGGLE_SIDE,
    /** AI opponent action. */
    AI_OPPONENT,
    /** Toggle timer action. */
    TOGGLE_TIMER,
    /** Settings action. */
    SETTINGS,
    /** Exit action. */
    EXIT
}
