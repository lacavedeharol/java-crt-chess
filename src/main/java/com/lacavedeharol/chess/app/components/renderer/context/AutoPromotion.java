package com.lacavedeharol.chess.app.components.renderer.context;

/**
 * Enum representing the auto-promotion options.
 */
enum AutoPromotion {
    /** Auto-promotion disabled. */
    OFF,
    /** Auto-promote to queen. */
    QUEEN,
    /** Auto-promote to rook. */
    ROOK,
    /** Auto-promote to bishop. */
    BISHOP,
    /** Auto-promote to knight. */
    KNIGHT
}
